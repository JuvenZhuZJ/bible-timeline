// Builds data/orbis.js: the route network of ORBIS, the Stanford Geospatial Network Model of the Roman World
// (W. Scheidel and E. Meeks, orbis.stanford.edu): its towns, ports and capes, and the roads, coastal and
// open-sea lanes and rivers between them, each with the days it takes in summer (one way; a sea lane can be
// faster one way than the other, with the winds). The data is the copy in the gorbit repository
// (github.com/sfsheath/gorbit, from github.com/emeeks/orbis_v2, MIT, and purl.stanford.edu/mn425tz9757, CC BY),
// kept in data/source/orbis/.
// Usage: node tools/build-orbis.mjs [data/source/orbis] [data/orbis.js]
import fs from 'fs';
import { seaWays } from './sea-way.mjs';
const dir = process.argv[2] || 'data/source/orbis', out = process.argv[3] || 'data/orbis.js';
const csv = (f) => fs.readFileSync(`${dir}/${f}`, 'utf8').trim().split('\n').slice(1)
  .map((l) => l.match(/("[^"]*"|[^,]+)/g).map((v) => v.replace(/^"|"$/g, '')));
// t: r road, c along the coast, o across the open sea, f ferry, v river
const TYPE = { road: 'r', coastal: 'c', slowcoast: 'c', overseas: 'o', slowover: 'o', ferry: 'f', upstream: 'v', downstream: 'v', fastup: 'v', fastdown: 'v' };
const n = {};
for (const [id, name, rank, x, y] of csv('gorbit-nodes.csv')) n[id] = [name, +(+x).toFixed(3), +(+y).toFixed(3), +rank];
const best = new Map();    // the quickest of the ways one way between two places
for (const [a, b, , days, , type] of csv('gorbit-edges.csv')) {
  if (!n[a] || !n[b] || !TYPE[type]) continue;
  const k = a + '>' + b, d = +(+days).toFixed(3);
  if (!best.has(k) || best.get(k)[2] > d) best.set(k, [+a, +b, d, TYPE[type]]);
}
const e = [...best.values()];
// a sea lane is a straight line from port to port in ORBIS; where that line would cross a cape or an island
// on the map, the lane is given the corners of a way around it across the water (tools/sea-way.mjs)
const S = seaWays(), bends = new Map();
let bent = 0;
for (const x of e) {
  if (x[3] === 'r' || x[3] === 'v') continue;
  const k = [x[0], x[1]].sort().join('>'), a = n[x[0]].slice(1, 3), b = n[x[1]].slice(1, 3);
  if (!bends.has(k)) {
    let via = null;
    if (S.landOn(a, b) >= 1) {
      const [p, q] = a < b ? [a, b] : [b, a], c = S.route(p, q);    // the same way in both directions
      const len = c && [p, ...c, q].reduce((t, r, i, all) => (i ? t + S.km(all[i - 1], r) : 0), 0);
      if (c && c.length && len <= 3 * S.km(a, b)) via = a < b ? c : c.slice().reverse();
    }
    bends.set(k, { via, a: x[0] });
  }
  const { via, a: from } = bends.get(k);
  if (via) { x.push(from === x[0] ? via : via.slice().reverse()); bent++; }
}
fs.writeFileSync(out, `/* ORBIS route network (generated by tools/build-orbis.mjs, do not edit).
 * ORBIS: The Stanford Geospatial Network Model of the Roman World, W. Scheidel and E. Meeks (orbis.stanford.edu).
 * Data: github.com/emeeks/orbis_v2 (MIT) and purl.stanford.edu/mn425tz9757 (CC BY), via github.com/sfsheath/gorbit.
 * n: { id: [name, longitude, latitude, rank] }
 * e: [from, to, days, type: r road, c coast, o open sea, f ferry, v river, corners around the land (a sea lane)] */
window.ORBIS = {"n":${JSON.stringify(n)},
"e":${JSON.stringify(e)}};
`);
console.log(`${Object.keys(n).length} places, ${e.length} ways (${bent} sea lanes bent around the land) -> ${out}`);
